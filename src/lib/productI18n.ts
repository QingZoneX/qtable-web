export type ProductMessageKey = keyof typeof zhCN;

export const productT = (
  key: ProductMessageKey,
  variables?: Record<string, string | number>,
) => {
  const language: Language = getLanguage();
  let value = language === "en-US" ? enUS[key] : zhCN[key];
  if (variables) {
    for (const [name, replacement] of Object.entries(variables)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
};

export const productLocale = (): Language => getLanguage();

export const productLocaleCompare = (left: string, right: string) =>
  left.localeCompare(right, productLocale());

export const productDateTime = (
  value: string | number | Date,
  options: Intl.DateTimeFormatOptions = {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
  },
) => new Intl.DateTimeFormat(productLocale(), options).format(new Date(value));
