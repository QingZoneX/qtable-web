type TableWorkspaceMessageKey = keyof (typeof messages)["zh-CN"];

export function tableWorkspaceT(
  key: TableWorkspaceMessageKey,
  variables?: Record<string, string | number>,
) {
  const language = getLanguage();
  let value: string = messages[language]?.[key] || messages["zh-CN"][key];
  if (variables) {
    for (const [name, replacement] of Object.entries(variables)) {
      value = value.replace(`{${name}}`, String(replacement));
    }
  }
  return value;
}
