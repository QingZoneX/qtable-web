type HomeMessageKey = keyof (typeof messages)["zh-CN"];

export const homeT = (
  key: HomeMessageKey,
  variables?: Record<string, string | number>,
) => {
  const language = getLanguage();
  let value: string = messages[language]?.[key] || messages["zh-CN"][key];
  if (variables) {
    Object.entries(variables).forEach(([name, replacement]) => {
      value = value.replace(`{${name}}`, String(replacement));
    });
  }
  return value;
};
