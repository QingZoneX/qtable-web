export type ProjectsCenterMessageKey = keyof typeof zhCN;

export const projectsT = (
  key: ProjectsCenterMessageKey,
  variables?: Record<string, string | number>,
) => {
  let value: string = getLanguage() === "en-US" ? enUS[key] : zhCN[key];
  if (variables) {
    for (const [name, replacement] of Object.entries(variables)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
};

export const projectsLocale = () => getLanguage();
