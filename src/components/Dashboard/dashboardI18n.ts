export type DashboardMessageKey = keyof typeof zhCN;

export function dashboardT(
  key: DashboardMessageKey,
  variables?: Record<string, string | number>,
): string {
  const language: Language = getLanguage();
  let value: string = language === "en-US" ? enUS[key] : zhCN[key];
  if (variables) {
    for (const [name, replacement] of Object.entries(variables)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export function dashboardOperatorLabel(operator: string): string {
  const key = `operator.${operator}` as DashboardMessageKey;
  return key in zhCN ? dashboardT(key) : operator;
}
